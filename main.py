# 4. نقطة الانطلاق الرئيسية
# ==========================================
if __name__ == "__main__":
    token = os.environ.get("TOKEN")
    if not token:
        print("CRITICAL ERROR: TOKEN environment variable not found!")
        exit(1)

    # تشغيل سيرفر الويب في الخلفية لفحص صحة Koyeb
    flask_thread = threading.Thread(target=run_flask_server, daemon=True)
    flask_thread.start()

    # تشغيل بوت التليجرام في الخيط الرئيسي
    application = ApplicationBuilder().token(token).build()
    application.add_handler(CommandHandler("start", start_command))
    application.add_handler(MessageHandler(filters.TEXT & (~filters.COMMAND), handle_buttons))

    print("Telegram Bot is running in Main Thread...")
    application.run_polling()
